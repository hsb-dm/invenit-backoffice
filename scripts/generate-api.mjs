import fs from 'node:fs';
import path from 'node:path';

const spec = JSON.parse(fs.readFileSync('openapi/admin.json', 'utf8'));
const tags = new Set([
	'admin-clients',
	'admin-kyc',
	'admin-subscriptions',
	'admin-products',
	'admin-advisors',
	'admin-finance',
	'admin-users',
	'admin-roles',
	'admin-dashboard',
	'admin-otp'
]);
const system = new Set(['/admin/menus', '/admin/dictionary', '/admin/dictionary/{type}']);
const operations = {};
const routes = new Map();
function expand(schema) {
	if (!schema) return {};
	if (schema.$ref) return expand(spec.components.schemas[schema.$ref.split('/').at(-1)]);
	return {
		...schema,
		...(schema.properties
			? {
					properties: Object.fromEntries(
						Object.entries(schema.properties).map(([k, v]) => [k, expand(v)])
					)
				}
			: {}),
		...(schema.items ? { items: expand(schema.items) } : {})
	};
}
for (const [url, methods] of Object.entries(spec.paths)) {
	for (const [method, op] of Object.entries(methods)) {
		if (!tags.has(op.tags?.[0]) && !system.has(url)) continue;
		const id = op.operationId;
		const local = '/api' + url;
		operations[id] = {
			method: method.toUpperCase(),
			path: local,
			upstream: url,
			summary: op.summary,
			parameters: op.parameters ?? [],
			schema: expand(op.requestBody?.content?.['application/json']?.schema)
		};
		const filename = 'src/routes' + local.replace(/\{([^}]+)\}/g, '[$1]') + '/+server.ts';
		if (!routes.has(filename)) routes.set(filename, []);
		routes
			.get(filename)
			.push(
				`export const ${method.toUpperCase()}: RequestHandler = (event) => handleOperation(event, '${id}');`
			);
	}
}
fs.writeFileSync(
	'src/lib/api/contract.ts',
	'// Generated by scripts/generate-api.mjs.\nexport const operations = ' +
		JSON.stringify(operations, null, 2) +
		' as const;\nexport type OperationId = keyof typeof operations;\n'
);
for (const [filename, exports] of routes) {
	fs.mkdirSync(path.dirname(filename), { recursive: true });
	fs.writeFileSync(
		filename,
		`// Generated explicit endpoint; regenerate with pnpm api:generate.\nimport type { RequestHandler } from './$types';\nimport { handleOperation } from '#lib/server/admin/handler.js';\n\n${exports.join('\n')}\n`
	);
}
